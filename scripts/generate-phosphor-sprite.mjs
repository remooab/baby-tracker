#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SPRITE_FILE = path.join(ROOT, 'phosphor-icons.svg');
const SOURCE_FILES = ['index.html', 'app.js'].map((file) => path.join(ROOT, file));

const ICON_ALLOWLIST = [
  'baby',
  'house',
  'bowl-food',
  'moon-stars',
  'sliders-horizontal',
  'drop',
  'jar',
  'jar-label',
  'flask',
  'pill',
  'plus-circle',
  'caret-left',
  'caret-right',
  'x',
  'cloud-moon',
];

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function parseSymbols(svg) {
  const symbolPattern = /<symbol id="ph-([a-z0-9-]+)"([^>]*)>([\s\S]*?)<\/symbol>/g;
  const symbols = new Map();

  for (const match of svg.matchAll(symbolPattern)) {
    const [, name, rawAttributes, rawContent] = match;
    symbols.set(name, {
      attributes: rawAttributes.trim(),
      content: rawContent.trim(),
    });
  }

  return symbols;
}

function indentBlock(content, spaces) {
  const prefix = ' '.repeat(spaces);
  return content
    .split('\n')
    .map((line) => `${prefix}${line.trim()}`)
    .join('\n');
}

async function findReferencedIcons(candidateIcons) {
  const referenced = new Set();

  for (const file of SOURCE_FILES) {
    const source = await readFile(file, 'utf8');

    for (const icon of candidateIcons) {
      const pattern = new RegExp(`ph-${escapeRegExp(icon)}\\b|['\"]${escapeRegExp(icon)}['\"]`);
      if (pattern.test(source)) {
        referenced.add(icon);
      }
    }
  }

  return referenced;
}

async function main() {
  const sprite = await readFile(SPRITE_FILE, 'utf8');
  const symbols = parseSymbols(sprite);

  const missingSymbols = ICON_ALLOWLIST.filter((icon) => !symbols.has(icon));
  if (missingSymbols.length > 0) {
    throw new Error(`Missing sprite symbols for: ${missingSymbols.join(', ')}`);
  }

  const referencedIcons = await findReferencedIcons([...symbols.keys()]);
  const missingFromAllowlist = [...referencedIcons].filter((icon) => !ICON_ALLOWLIST.includes(icon));

  if (missingFromAllowlist.length > 0) {
    throw new Error(
      `Referenced icons are missing from ICON_ALLOWLIST: ${missingFromAllowlist.join(', ')}`,
    );
  }

  const unusedIcons = ICON_ALLOWLIST.filter((icon) => !referencedIcons.has(icon));
  const lines = [
    '<!-- Generated by `npm run icons:build`. Update ICON_ALLOWLIST in scripts/generate-phosphor-sprite.mjs when icon usage changes. -->',
    '<svg xmlns="http://www.w3.org/2000/svg" style="display: none;">',
  ];

  for (const icon of ICON_ALLOWLIST) {
    const symbol = symbols.get(icon);
    const attributeSuffix = symbol.attributes ? ` ${symbol.attributes}` : '';
    lines.push(`  <symbol id="ph-${icon}"${attributeSuffix}>`);
    lines.push(indentBlock(symbol.content, 4));
    lines.push('  </symbol>');
  }

  lines.push('</svg>');
  lines.push('');

  await writeFile(SPRITE_FILE, lines.join('\n'), 'utf8');

  console.log(`Wrote ${ICON_ALLOWLIST.length} curated icons to ${path.basename(SPRITE_FILE)}.`);
  if (unusedIcons.length > 0) {
    console.log(`Unused allowlist entries: ${unusedIcons.join(', ')}`);
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});